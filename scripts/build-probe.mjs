// Compiles contracts/TransferProbe.sol and writes its runtime bytecode to src/core/probe.generated.ts.
import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync("contracts/TransferProbe.sol", "utf8");
const input = {
  language: "Solidity",
  sources: { "TransferProbe.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["evm.deployedBytecode.object", "abi"] } },
  },
};

// Uses the compiler bundled with the pinned solc package, so the output is reproducible offline.
const compiler = solc;

const output = JSON.parse(compiler.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}
const contract = output.contracts["TransferProbe.sol"].TransferProbe;
const file = `// Generated by scripts/build-probe.mjs from contracts/TransferProbe.sol (solc ${compiler.version()}). Do not edit.
export const TRANSFER_PROBE_RUNTIME = "0x${contract.evm.deployedBytecode.object}" as const;

export const TRANSFER_PROBE_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;
`;
writeFileSync("src/core/probe.generated.ts", file);
console.log(
  `Wrote src/core/probe.generated.ts (${contract.evm.deployedBytecode.object.length / 2} bytes, solc ${compiler.version()})`,
);
